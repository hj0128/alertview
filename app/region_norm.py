def _landmark(tokens):
    for x in tokens:
        base = re.sub(r"(역|동)$", "", x)     # 성수역/성수동 → 성수
        hit = LANDMARK.get(x) or LANDMARK.get(base)
        if hit:
            return f"{hit[0]} {hit[1]}"
    return ""


def _find_sido(tokens):
    for x in tokens:
        s = SIDO_ALIASES.get(x)
        if s:
            return s, x
    return None, None


def normalize_offline(raw: str) -> str:
    """내장 사전으로 '시/도 시군구'(또는 '시/도') 반환. 못 잡으면 ''."""
    if not raw:
        return ""
    tokens = [t for t in re.split(r"[\s/]+", raw.strip()) if t]
    if not tokens:
        return ""
    sido, sido_tok = _find_sido(tokens)

    if sido and SIDO_SIGUNGU.get(sido):
        for x in tokens:
            if x == sido_tok:              # 시/도 토큰 자체는 시군구로 오인하지 않게 건너뜀
                continue
            xs = x.rstrip("역")           # '강남역' -> '강남'
            for full in SIDO_SIGUNGU[sido]:
                if xs == full or xs == _short(full):
                    return f"{sido} {full}"
        return _landmark(tokens) or sido   # 시군구 못 찾으면 동/번화가로 보강, 아니면 시/도

    if sido:                               # 세종 등 시군구 없는 단층
        return _landmark(tokens) or sido

    # 시/도 토큰이 없을 때: 유일하게 결정되는 시군구 찾기(역/동 접미사 정리 포함)
    for x in tokens:
        for cand in (x, x.rstrip("역"), _short(x)):
            hit = UNIQUE_SIGUNGU.get(cand) or UNIQUE_SIGUNGU.get(_short(cand))
            if hit:
                return f"{hit[0]} {hit[1]}"
    # 동/역/번화가 시드 매핑(예: 성수 → 서울 성동구)
    return _landmark(tokens)


def region_from_title(title: str) -> str:
    """제목에서 '위치'를 나타내는 후보 문자열만 추출(정규화 전).
    - 대괄호 중 '유형/채널' 태그(기자단·배송·블로그 등)는 건너뛰고, 위치 대괄호만 사용.
    - 위치 대괄호가 없으면, 맨 앞 단어가 '시/도'일 때만 사용(가게이름 오인 방지).
    예: '[기자단] 타코부스 NYC 성수점' → ''(위치 아님),  '[성수] 코코로반' → '성수',
        '[서울 송파구] 더기타레슨' → '서울 송파구',  '[블로그+클립][울산] ..' → '울산'.
    """
    if not title:
        return ""
    for b in re.findall(r"\[([^\]]+)\]", title):
        b2 = b.replace("+", " ").replace("/", " ").strip()
        toks = [t for t in b2.split() if t]
        loc = [t for t in toks if t not in TYPE_MARKERS]
        if not loc:                # 전부 유형태그 → 위치 아님, 다음 대괄호로
            continue
        return " ".join(loc)       # 첫 위치 대괄호의 위치 토큰들
    # 대괄호에 위치 없음 → 앞 단어가 시/도면만 채택
    rest = re.sub(r"\[[^\]]*\]", " ", title).split()
    if rest and SIDO_ALIASES.get(rest[0]):
        return rest[0]
    return ""
